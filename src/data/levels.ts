export function parseLevel(levelNumber: number): ParsedLevel {
  const index = Math.max(0, Math.min(RAW_LEVELS.length - 1, levelNumber - 1));
  const [par, code] = RAW_LEVELS[index];

  const vehicles: Vehicle[] = [
    {
      id: 0,
      h: true,
      len: 2,
      fx: 0,
      fy: 2,
      color: PLAYER_VEHICLE.color,
      secondaryColor: PLAYER_VEHICLE.secondary,
      type: 'player',
      name: PLAYER_VEHICLE.name,
    },
  ];

  const startPos: number[] = [parseInt(code[0], 10)];

  let vehicleIdx = 1;
  for (let i = 1; i + 3 < code.length; i += 4) {
    const isHorizontal = code[i] === '1';
    const length = parseInt(code[i + 1], 10);
    const fixedPos = parseInt(code[i + 2], 10);
    const initialPos = parseInt(code[i + 3], 10);
    const palette = VEHICLE_PALETTES[(vehicleIdx - 1) % VEHICLE_PALETTES.length];

    vehicles.push({
      id: vehicleIdx,
      h: isHorizontal,
      len: length,
      fx: isHorizontal ? 0 : fixedPos,
      fy: isHorizontal ? fixedPos : 0,
      color: palette.color,
      secondaryColor: palette.secondary,
      type: length === 3 ? 'truck' : 'car',
      name: palette.name,
    });

    startPos.push(initialPos);
    vehicleIdx++;
  }

  return {
    id: levelNumber,
    par,
    vehicles,
    startPos,
  };
}

